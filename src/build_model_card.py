"""
docs/model_card.md - the attrition model's instructions for use, written from the numbers.

The AI Act register in ai-act-hr-readiness-kit lists this model as system S07: high-risk under Annex III
point 4(b), built in-house, so the employer is its provider (Art. 3(3) and 16) and has to answer, as a
provider would, the questions it sends every supplier. This file answers them in the register's order
(V01-V11, V14-V16), with every figure computed by the same code that tested the model, so the card
cannot drift from the evidence.
"""

from __future__ import annotations

import math

from analysis_fairness import COUNTRY_NAMES, FLAG_SHARE, audit
from analysis_validation import HORIZON, TESTS, TRAIN, evaluate
from hrlib import ROOT, md_table

CARD = ROOT / "docs" / "model_card.md"
KIT = "https://github.com/D0M3N1C0X/ai-act-hr-readiness-kit"

# What would make the next refit unfit to use: checked on the latest unseen quarter before release.
GATES = {"AUC out of time": "0.70 or more", "Predicted against observed, all staff": "within 1 point",
         "Calibration slope": "between 0.8 and 1.2", "Any group of 20+ resignations": "calibration gap under 3 standard errors"}


def pct(x: float, d: int = 1) -> str:
    return f"{x:.{d}%}"


def build() -> str:
    v = evaluate()
    a = audit(v["scored"])
    m, model = v["pooled"]["model"], v["model"]
    flagged = [(p, y) for _, p, y in v["scored"] if p >= a["cut"]]
    hit_rate = sum(y for _, y in flagged) / len(flagged)
    odds = sorted(((name, math.exp(model.get(name)), model.p(name)) for name in v["drivers"]), key=lambda t: -t[1])
    tests = " and ".join(f"{c:%-d %B %Y}" for c in TESTS)

    # One worked explanation, for the highest score in the last unseen quarter (a synthetic person)
    person, score = max(((r, p) for r, p, _ in v["scored"] if r["cutoff"] == TESTS[-1]), key=lambda t: t[1])
    weight = {name: o for name, o, _ in odds}
    plain = {
        "Paid below band (compa-ratio < 0.92)": "pay below 92% of the mid-point of your band",
        "No promotion in 24+ months": "no promotion in the last two years",
        "Engagement in bottom quartile": "a survey score in the bottom quarter",
        "Fixed-term contract": "a fixed-term contract",
        "First year of tenure": "less than a year with the company",
        "Fully onsite": "a fully onsite role",
        f"Works in {v['department']}": f"working in {v['department']}",
        "Reopened HR case in Q1": "an HR request that had to be reopened in the last three months",
    }
    signs = [f"{plain[name]} ({weight[name]:.1f} times the odds)" for name, test in v["drivers"].items()
             if test(person)]
    young, old = a["groups"]["Age"]["under 30"], a["groups"]["Age"]["45 and over"]
    country = a["groups"]["Country"]
    over = max(country, key=lambda c: country[c]["predicted"] / country[c]["observed"])
    under = min(country, key=lambda c: country[c]["predicted"] / country[c]["observed"])
    engagement = next(t for t in odds if t[0] == "Engagement in bottom quartile")
    q1, q2 = (v["tests"][c]["model"] for c in TESTS)

    group_rows = []
    for dim, rows in a["groups"].items():
        for level, g in rows.items():
            group_rows.append([dim, level, f"{g['n']:,}", str(g["events"]), pct(g["observed"]), pct(g["predicted"]),
                               f"{g['z']:+.1f}", f"{g['auc']:.2f}", f"{g['caught']:.0%}", pct(g["false_flags"])])
    test_rows = [[f"{c:%b %Y}", f"{t['model']['n']:,}", str(t["model"]["events"]),
                  f"{t['model']['auc']:.2f} ({t['model']['ci'][0]:.2f}-{t['model']['ci'][1]:.2f})",
                  f"{t['model']['top10']:.0%}", pct(t["model"]["predicted"]), pct(t["model"]["observed"])]
                 for c, t in v["tests"].items()]

    md = f"""# Model card: attrition-risk model (S07)

*Generated by `python3 src/run_all.py` from the code that fits and tests the model. Synthetic data;
the structure, not the figures, is what carries over to a real deployment.*

| | |
|---|---|
| **System** | S07 in the [AI Act register]({KIT}), "Attrition-risk model" |
| **Classification** | High-risk, Annex III point 4(b): it evaluates individuals and shapes decisions on terms of work |
| **Role** | Provider and deployer: built and put into service by HR analytics for the employer's own use (Art. 3(3), 16) |
| **Version** | 1.0: logistic regression on eight inputs, fitted on staff at risk on {TRAIN:%-d %B %Y} |
| **Tested** | on staff at risk on {tests}, a {HORIZON}-month outcome each, quarters it never saw |
| **High-risk duties apply** | at its next significant design change (Art. 111(2)), and the first change planned below is one |

The register asks every supplier of a high-risk system the same questions. Because this one is built
in-house, the team that built it answers them, in the register's order.

## V01 · Instructions for use (Art. 13(2)-(3))

This card is the instructions for use.

**Intended purpose.** To help HR business partners decide **where to offer stay conversations** in the
coming quarter: which teams carry the most risk, and which of the eight warning signs drive it there.

**Not for**, whatever the score says:
- pay, bonuses or counter-offers: a pay decision taken on a predicted intention to leave is unequal
  treatment waiting to happen, and pay has its own process;
- promotion, training, assignments, performance ratings or any disciplinary step;
- dismissal, contract renewal or redundancy selection;
- any decision about a person that the person cannot see and contest.

The register currently describes managers using the score for retention conversations **and
counter-offers**. This card narrows that: counter-offers are out of scope.

## V02 · Accuracy and robustness (Art. 13(3)(b)(ii)-(iii))

| Scored on | At risk | Resigned | AUC (95% CI) | Resigners in top 10% | Predicted | Observed |
|---|---:|---:|---:|---:|---:|---:|
{chr(10).join("| " + " | ".join(r) + " |" for r in test_rows)}
| **Both quarters** | **{m['n']:,}** | **{m['events']}** | **{m['auc']:.2f} ({m['ci'][0]:.2f}-{m['ci'][1]:.2f})** | **{m['top10']:.0%}** | **{pct(m['predicted'])}** | **{pct(m['observed'])}** |

Calibration slope {m['slope']:.2f}; Brier score {m['brier']:.4f}. Counting the same eight signs without
weights reaches an AUC of {v['pooled']['checklist_auc']:.2f}; the most any model could reach on this data
is {v['pooled']['ceiling']['auc']:.2f}.

**What a flag means.** At the top-{FLAG_SHARE:.0%} cut, **{hit_rate:.0%} of flagged people resign within
the quarter and {1 - hit_rate:.0%} stay.** A flag is a reason to talk, not a prediction about a person.

**Circumstances known to affect it.**
- **Quarter to quarter**, the AUC moved from {q1['auc']:.2f} to {q2['auc']:.2f}. The intervals overlap, so
  that is within chance; a deployment should still watch whether January, the pay-review quarter, is
  reliably weaker, because that is when pay grievances surface.
- **New joiners** have no case history before their third month, so one input is always zero for them.
- **A change to pay bands** moves the compa-ratio input for everyone at once; refit after any band review.
- **Reorganisations** break the department input; refit after any change of department structure.
- **Cybersecurity**: the model runs offline in Python's standard library with no network access; the risk
  sits in the HR data it reads, which stays under the HRIS's access controls.

## V03 · Performance by group (Art. 13(3)(b)(v))

Scores from both unseen quarters, one company-wide cut (top {FLAG_SHARE:.0%}). The z column is the gap
between resignations observed and predicted, in standard errors: beyond ±2 it is unlikely to be chance.

{md_table(["Group", "", "At risk", "Resigned", "Observed", "Predicted", "z", "AUC", "Resigners caught", "Stayers flagged"], group_rows, align="llrrrrrrrr")}

**Known issues.** {COUNTRY_NAMES[over]} is over-predicted ({pct(country[over]['predicted'])} against
{pct(country[over]['observed'])}, z {country[over]['z']:+.1f}) and {COUNTRY_NAMES[under]} under-predicted, because country of
work is not an input; the fix is planned for version 1.1 (V07). Staff under 30 are flagged
{young['flag_rate'] / old['flag_rate']:.1f} times as often as staff over 45, through tenure and contract
type: acceptable for an offer of a conversation, not for anything that could disadvantage them, which is
why V01 rules those uses out.

## V04 · Human oversight (Art. 13(3)(d); 14; 26(2))

- **Who sees scores.** The HR business partner for the team, and the named overseer. Line managers see a
  team-level count of flags and the signs behind them, **never a ranked list of names**.
- **Overseer.** [Name and deputy], trained on this card and on literacy module L02 of the register, with
  the authority to suspend the model.
- **Every use is a human decision.** A conversation is offered or not by the business partner; the score
  never triggers anything on its own. GDPR Art. 22 is not engaged because no decision is based solely on
  automated processing, and the oversight has to stay real for that to remain true.
- **Overriding** is expected and logged: a business partner who knows a flag is wrong records why.
- **Stop rule.** Suspend the model if a release gate in V07 fails on a new quarter, or if a group's
  calibration gap passes 3 standard errors.

## V05 · Input data, and the data it was trained and tested on (Art. 13(3)(b)(vi); 26(4))

| Input | Odds ratio | p | Source |
|---|---:|---:|---|
{chr(10).join(f"| {name} | {o:.2f} | {'<0.001' if p < 0.001 else f'{p:.3f}'} | {src} |" for (name, o, p), src in zip(odds, [{
    "Paid below band (compa-ratio < 0.92)": "payroll and pay bands",
    "No promotion in 24+ months": "HRIS job history",
    "Engagement in bottom quartile": "engagement survey (team-level release rules apply)",
    "Fixed-term contract": "HRIS contract",
    "First year of tenure": "HRIS hire date",
    "Fully onsite": "HRIS work model",
    f"Works in {v['department']}": "HRIS organisation",
    "Reopened HR case in Q1": "HR service desk",
}[name] for name, _, _ in odds]))}

These are the weights of the version tested, fitted on one quarter; the driver analysis in the report,
fitted on nine months, finds the same order with somewhat different sizes.

**The engagement input needs a decision before any real use.** Most engagement surveys promise that no
individual answer reaches management; feeding an individual's score to this model breaks that promise.
Unless the survey was run as identified and people were told it feeds this model, drop the input. Its
weight is {engagement[1]:.2f} (p = {engagement[2]:.2f}), so little is lost.

**Not used, by design:** sex, age, nationality, country of work (until version 1.1), health, absence
records, union membership, family status. **Trained on** {v['train']['n']:,} employees at risk on
{TRAIN:%-d %B %Y} ({v['train']['events']} resigned in the quarter). **Tested on** {m['n']:,}
person-quarters at {tests}.

## V06 · Logs (Art. 12; 13(3)(f); 26(6))

Each scoring run records: the date, the model version, a hash of the input snapshot, every score, who
viewed which team, and what was done (conversation offered, declined, overridden, with the reason).
Kept **at least six months** (Art. 26(6)); twelve is better, to cover a full review cycle. *This
repository does not implement the log: a deployment must.*

## V07 · Changes, and what counts as significant (Art. 13(3)(c); 111(2))

**Pre-determined change:** a quarterly refit of the same eight inputs, released only if it passes on the
latest unseen quarter:

{md_table(["Release gate", "Threshold"], [[k, val] for k, val in GATES.items()], align="ll")}

**Anything else is a significant change**: a new input, a new outcome, a new use. **Version 1.1, adding
country of work to fix V03, is one.** It ends the Art. 111(2) grace period, so the provider's duties
(V11) must be in place before it ships, and the workers' representatives are told first (V15).

## V08 · Contact and serious incidents (Art. 26(5); 72; 73)

[Model owner, HR analytics], [overseer]. A risk to health, safety or fundamental rights is reported to
the owner the same day; the model is suspended while it is examined.

## V09 · For the data protection impact assessment (Art. 13; 26(9); GDPR Art. 35)

Purpose as in V01; inputs and exclusions as in V05; profiling within the meaning of GDPR Art. 4(4),
without decisions based solely on it (V04); no special categories of data; scores kept with the logs (V06)
and then deleted. The register's draft impact assessment for S07 takes these as its section (a) to (f).

## V10 · Explaining an individual output (Art. 13(3)(b)(iv); 86)

A score is explained by the warning signs that apply to the person and how much each weighs. For the
highest score in the last test quarter (a synthetic employee):

> Your team's retention review flagged a higher than usual chance of leaving, **{pct(score)}** in the
> next three months against **{pct(m['observed'])}** across the company. It comes from
> {"; ".join(signs)}. Nothing was decided from it. You can ask HR to correct any of these facts,
> and to have the flag removed.

The odds are relative to a colleague without that sign; they combine, which is why one person can reach a
score this high. The explanation is given to the person on request, not sent to their manager.

## V11 · Conformity assessment and registration (Art. 16(f)-(i); 47-49)

**Not done.** Before the first significant change (V07), the provider needs: a quality management system
(Art. 17), technical documentation (Annex IV, for which this card is a start), an internal-control
conformity assessment (Annex VI), an EU declaration of conformity, the CE marking and registration in the
EU database (Art. 49).

## V14 · Emotions (Art. 5(1)(f))

The model infers no emotions. The engagement survey score is a self-reported answer, not an inference.

## V15 · For the national notices to workers

The logic is a logistic regression; the main parameters are the eight inputs and odds ratios in V05;
the data categories are those in its source column. That is what the Italian notice (D.lgs. 152/1997
art. 1-bis co. 2) and Spain's works-council information (ET art. 64.4.d) ask for; in Germany the model
needs a works agreement before use (BetrVG §87(1) Nr. 6). The register sets out which rule applies where.

## V16 · Training (Art. 4)

Everyone who sees a score learns three things first: the base rate is {pct(m['observed'])} a quarter; a
flagged person stays {1 - hit_rate:.0%} of the time; and the uses in V01 that are ruled out are ruled out
whatever the score says. Module L02 of the register covers the rest.
"""
    return md


def main() -> None:
    CARD.parent.mkdir(exist_ok=True)
    CARD.write_text(build(), encoding="utf-8")
    print(f"     docs/model_card.md")


if __name__ == "__main__":
    main()
